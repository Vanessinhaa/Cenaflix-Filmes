/**
 * Filtra os filmes pela categoria informada.
 */
private void filtrarFilmes() {
    String categoria = txtPesquisa.getText().trim();

    if (categoria.isEmpty()) {
        carregarFilmes();
        return;
    }

    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) jTable1.getModel();

    modelo.setRowCount(0);

    String sql = "SELECT id, nome, datalancamento, categoria "
               + "FROM filmes WHERE categoria LIKE ?";

    try (java.sql.Connection conn = Conexao.conectar();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, "%" + categoria + "%");

        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("nome"),
                    rs.getString("datalancamento"),
                    rs.getString("categoria")
                });
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Não foi possível pesquisar os filmes: " + e.getMessage()
        );
    }
}

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // TODO add your handling code here:
  
int linha = jTable1.getSelectedRow();

if (linha == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Selecione um filme na tabela para atualizar!"
    );
    return;
}

int id = Integer.parseInt(
    jTable1.getValueAt(linha, 0).toString()
);

String nome = jTable1.getValueAt(linha, 1).toString();
String data = jTable1.getValueAt(linha, 2).toString();
String categoria = jTable1.getValueAt(linha, 3).toString();

try {
    java.time.LocalDate dataConvertida =
        java.time.LocalDate.parse(data);

    data = dataConvertida.format(
        java.time.format.DateTimeFormatter.ofPattern("dd/MM/uuuu")
    );
} catch (java.time.format.DateTimeParseException e) {
    // Se a tabela já mostrar a data em outro formato,
    // será necessário ajustar a conversão.
}

TelaCadastrosFilmes tela = new TelaCadastrosFilmes();
tela.carregarParaEdicao(id, nome, data, categoria);
tela.setLocationRelativeTo(null);
tela.setVisible(true);

    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        
int linha = jTable1.getSelectedRow();

if (linha == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Selecione um filme na tabela para excluir!"
    );
    return;
}

int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
    this,
    "Tem certeza de que deseja excluir este filme?",
    "Confirmar exclusão",
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirmacao != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

int id = Integer.parseInt(
    jTable1.getValueAt(linha, 0).toString()
);

String sql = "DELETE FROM filmes WHERE id = ?";

try (java.sql.Connection conn = Conexao.conectar();
     java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

    stmt.setInt(1, id);

    int resultado = stmt.executeUpdate();

    if (resultado > 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Filme excluído com sucesso!"
        );
        carregarFilmes();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Nenhum filme foi excluído."
        );
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Erro ao excluir: " + e.getMessage()
    );
}

    }//GEN-LAST:event_btnExcluirActionPerformed

