    /**
     * Carrega os filmes cadastrados no banco de dados
     * e os exibe na tabela.
     */
    private void carregarFilmes() {
        javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0);

        String sql = "SELECT id, nome, datalancamento, categoria FROM filmes";

        try (java.sql.Connection conn = Conexao.conectar();
             java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
             java.sql.ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("nome"),
                    rs.getString("datalancamento"),
                    rs.getString("categoria")
                });
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Não foi possível consultar os filmes: " + e.getMessage()
            );
        }
    }

