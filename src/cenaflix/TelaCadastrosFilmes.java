    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        // TODO add your handling code here:
       
String nome = txtNome.getText().trim();
String data = txtData.getText().trim();
String categoria = txtCategoria.getText().trim();

if (nome.isEmpty() || data.isEmpty() || categoria.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Preencha todos os campos!",
        "Atenção",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

try {
    java.time.LocalDate dataConvertida =
        java.time.LocalDate.parse(
            data,
            java.time.format.DateTimeFormatter.ofPattern("dd/MM/uuuu")
        );

    String sql;

    if (idFilmeEdicao == -1) {
        sql = "INSERT INTO filmes "
            + "(nome, datalancamento, categoria) VALUES (?, ?, ?)";
    } else {
        sql = "UPDATE filmes SET nome = ?, "
            + "datalancamento = ?, categoria = ? WHERE id = ?";
    }

    try (java.sql.Connection conexao = Conexao.conectar();
         java.sql.PreparedStatement comando =
             conexao.prepareStatement(sql)) {

        comando.setString(1, nome);
        comando.setDate(2, java.sql.Date.valueOf(dataConvertida));
        comando.setString(3, categoria);

        if (idFilmeEdicao != -1) {
            comando.setInt(4, idFilmeEdicao);
        }

        int resultado = comando.executeUpdate();

        if (resultado > 0) {
            String mensagem = idFilmeEdicao == -1
                ? "Filme cadastrado com sucesso!"
                : "Filme atualizado com sucesso!";

            javax.swing.JOptionPane.showMessageDialog(this, mensagem);

            idFilmeEdicao = -1;
            btnCadastrar.setText("Cadastrar");
            setTitle("Cenaflix - Cadastro de Filme");

            txtNome.setText("");
            txtData.setText("");
            txtCategoria.setText("");
            txtNome.requestFocusInWindow();
        }
    }

} catch (java.time.format.DateTimeParseException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Digite a data no formato dd/MM/aaaa. Exemplo: 20/10/2026",
        "Data inválida",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Não foi possível salvar o filme: " + e.getMessage(),
        "Erro no banco de dados",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
}


     
    }//GEN-LAST:event_btnCadastrarActionPerformed

